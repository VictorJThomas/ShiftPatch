import { sql } from "drizzle-orm";
import { boolean, check, date, index, integer, pgEnum, pgTable, text, time, uniqueIndex } from "drizzle-orm/pg-core";
import { createdAt, timestamps, tstz } from "./_common.js";
import { agencies, hospitalNetworks, nurseProfiles, users } from "./identity.js";
import { shifts } from "./shifts.js";

// Timesheets (ARCHITECTURE §4 "timesheets", promoted from [Future] on 2026-11-10). Times are wall-clock in the shift's
// timezone, like shifts.start_time/end_time: clock_out <= clock_in means the nurse clocked out the next day.
export const timesheetStatus = pgEnum("timesheet_status", ["submitted", "approved", "disputed"]);

export const timesheets = pgTable(
  "timesheets",
  {
    id: text().primaryKey(),
    shiftId: text().notNull().references(() => shifts.id, { onDelete: "restrict" }),
    nurseId: text().notNull().references(() => nurseProfiles.userId, { onDelete: "restrict" }),
    clockIn: time().notNull(),
    clockOut: time().notNull(),
    breakMinutes: integer().notNull().default(0),
    note: text(),
    status: timesheetStatus().notNull().default("submitted"),
    submittedAt: tstz().notNull().defaultNow(),
    reviewedBy: text().references(() => users.id, { onDelete: "restrict" }),
    reviewedAt: tstz(),
    reviewNote: text(),
    ...timestamps(),
  },
  (t) => [
    uniqueIndex("timesheets_shift_nurse_uq").on(t.shiftId, t.nurseId).where(sql`${t.deletedAt} IS NULL`),
    check("timesheets_break_range", sql`${t.breakMinutes} >= 0 AND ${t.breakMinutes} <= 240`),
    check("timesheets_times_differ", sql`${t.clockIn} <> ${t.clockOut}`),
    check("timesheets_reviewed_iff_not_submitted", sql`(${t.status} = 'submitted') = (${t.reviewedAt} IS NULL)`),
    index("timesheets_nurse_idx").on(t.nurseId),
  ],
);

// Inspection packages (ESCALATION.md Option D, approved by Victor 2026-11-10): a scoped, expiring, audited credential report
// for selected nurses and a period. No file bytes are stored here: documents are served through the existing short-lived
// signed links, only for credentials inside the package's scope, while the package is unexpired and not revoked.
export const inspectionPackages = pgTable(
  "inspection_packages",
  {
    id: text().primaryKey(),
    networkId: text().notNull().references(() => hospitalNetworks.id, { onDelete: "restrict" }),
    agencyId: text().references(() => agencies.id, { onDelete: "restrict" }), // null = generated by a network admin
    createdBy: text().notNull().references(() => users.id, { onDelete: "restrict" }),
    nurseIds: text().array().notNull(),
    periodFrom: date({ mode: "string" }).notNull(),
    periodTo: date({ mode: "string" }).notNull(),
    includeDocuments: boolean().notNull().default(false),
    includeTbDocuments: boolean().notNull().default(false), // opt-in; default shows "screening on file + date" only
    expiresAt: tstz().notNull(),
    revokedAt: tstz(),
    createdAt: createdAt(),
  },
  (t) => [
    check("inspection_packages_period", sql`${t.periodTo} >= ${t.periodFrom}`),
    check("inspection_packages_nurses", sql`cardinality(${t.nurseIds}) BETWEEN 1 AND 200`),
    check("inspection_packages_tb_needs_docs", sql`NOT ${t.includeTbDocuments} OR ${t.includeDocuments}`),
    index("inspection_packages_network_idx").on(t.networkId, t.createdAt),
  ],
);
